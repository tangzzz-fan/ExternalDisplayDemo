import SwiftUI

/// 幕墙的材质参数。
///
/// ## 为什么单独一个类型
/// 这几个数没有几何含义 —— 它们不参与任何位移计算，只决定"板透不透光"。
/// 塞进 `LateralMetrics` / `ScrollMetrics` 会让那两个纯几何类型（CoreGraphics only，
/// 能被验收脚本直接编译）开始依赖 SwiftUI，得不偿失。
///
/// ## 需求：玻璃幕墙，不是墙
/// 原设计里容器底是**刻意不透明**的，注释也写得很清楚："否则星海会从卡片缝隙里
/// 透上来，背景墙的『墙』就立不住了"。这一版要的正是它的反面 ——
/// 一块浮在星海之上的**玻璃板**：板自身半透光，列与列之间的缝里能看到星海。
///
/// ## 为什么不做模糊（`.ultraThinMaterial`）
/// 外接屏侧没有虚拟化，36 张卡一次性建出（`ExternalDisplayRootView.itemCount`）。
/// 给每张卡挂 backdrop blur 就是每帧 36 次离屏采样，而背后的星海还在动 ——
/// 4K 上是必然掉帧。更要紧的是方向不对：模糊会把星点糊成雾，
/// 而需求要的是"看清后面的星星海"。所以玻璃感靠**半透 + 白描边 + 同侧高光**
/// 这三样现成的东西撑，模糊一点都不加。
enum WallMaterial {

    /// 容器底板的不透明度。
    ///
    /// 这是"缝里能不能看到星星"的唯一开关：
    /// - `1` = 回到不透明底，`columnSpacing` 那条缝里只有底色（R6 不成立）；
    /// - `0` = 完全没有板，卡片像各自浮在星海里（"幕墙"不成立）。
    ///
    /// `0.58` 落在两者之间：星点被压到约四成亮度，仍然清晰可辨；
    /// 而板本身读起来是一块深蓝黑的玻璃，不是一块挖了洞的黑纸。
    static let plateOpacity: Double = 0.58

    /// 卡片填充的不透明度。
    ///
    /// 卡片半透之后，卡后面隐约有星 —— 这是"磨砂玻璃"的观感来源。
    /// 但**不能再低**：卡片上的编号与底栏文字是实心绘制的，底面太透会让文字
    /// 陷进星点里读不出来。文字的可读性优先于玻璃感。
    static let cardFillOpacity: Double = 0.84

    /// 底板颜色。卡片底栏也用它 —— 一块板上不该有第二种底色。
    static let plate = Color(red: 0.004, green: 0.005, blue: 0.014)
}
